import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../apps/storefront/package.json',import.meta.url));
const Parser=require('@apidevtools/swagger-parser');
const Ajv=require('ajv/dist/2020');
const formats=require('ajv-formats');
const contract=new URL('../contracts/commerce.openapi.yaml',import.meta.url).pathname;
await Parser.validate(contract);
const ajv=new Ajv({strict:true});formats(ajv);
const schema=JSON.parse(readFileSync(new URL('../contracts/catalog-event.schema.json',import.meta.url),'utf8'));
const validate=ajv.compile(schema);
const id='b2ea4fd6-e3ce-481d-99f1-4ff88dfe2e33';
const event={eventId:id,type:'OfferSnapshot',schemaVersion:1,aggregateId:id,version:1,occurredAt:new Date().toISOString(),offer:{id,productId:id,title:'Fixture',category:'Ceramics',description:'Test',sellerId:'seller-a',sellerName:'Studio',pricePaise:100,available:1,status:'PUBLISHED',version:1}};
assert.equal(validate(event),true,JSON.stringify(validate.errors));
assert.equal(validate({...event,schemaVersion:2}),false);
assert.equal(validate({...event,offer:{...event.offer,pricePaise:1.5}}),false);
assert.equal(validate({...event,offer:{...event.offer,status:'DRAFT'}}),false);
console.log('OpenAPI 3.1 and catalog event schema validated; invalid versions, fractional money and private snapshots rejected.');
const shipmentValidator=ajv.compile(JSON.parse(readFileSync(new URL('../contracts/fulfillment-event.schema.json',import.meta.url),'utf8')));
const shipment={eventId:id,type:'FulfillmentChanged',schemaVersion:1,aggregateId:id+':seller-a',checkoutId:id,sellerId:'seller-a',state:'PACKED',version:1,occurredAt:new Date().toISOString()};
assert.equal(shipmentValidator(shipment),true,JSON.stringify(shipmentValidator.errors));
assert.equal(shipmentValidator({...shipment,state:'PAID'}),false);
assert.equal(shipmentValidator({...shipment,version:0}),false);
assert.equal(shipmentValidator({...shipment,address:'private'}),false);
console.log('Fulfillment event schema validated; invalid states, versions and personal data rejected.');
